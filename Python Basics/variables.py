age = 20
print(type(age))

# Type Conversion
age = str(age)
print(age)
print(type(age))

## Dynamic Typing
## Python allows the type of a variable to change as the program Executes.

var = 10
print(var, type(var))

var = "Arpit"
print(var, type(var))

var = 5.7
print(var, type(var))

## input
age = int(input("Enter your age: "))
print(age, type(age))